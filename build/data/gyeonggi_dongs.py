def all_dongs():
    out = []
    for slug, dongs in DONGS.items():
        for name, ds, zone, near, char_line in dongs:
            out.append({"name":name,"slug":ds,"zone":zone,"near":near,"char":char_line,"district_slug":slug})
    return out

