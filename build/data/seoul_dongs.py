def all_seoul_dongs():
    """모든 행정동을 (district_slug, dong_dict) 튜플로 yield."""
    out = []
    for dslug, dongs in DONGS_BY_DISTRICT.items():
        for name, slug, zone, near, char in dongs:
            out.append({
                "name": name, "slug": slug, "zone": zone, "near": near, "char": char,
                "district_slug": dslug,
            })
    return out


def total_count():
    return sum(len(v) for v in DONGS_BY_DISTRICT.values())
